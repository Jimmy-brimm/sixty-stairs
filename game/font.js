// glyph -> { w, rows: [[x, ...lit columns] per row] }
export const FONT = {}
for (const [ch, art] of Object.entries(GLYPHS)) {
  const rows = art.split(' ')
  FONT[ch] = { w: rows[0].length, rows: rows.map(r => [...r].map((c, x) => c === '#' ? x : -1).filter(x => x >= 0)) }
}
export const GLYPH_H = 7
export const LOWER = {}
for (const [ch, art] of Object.entries(SMALL)) {
  const rows = art.split(' ')
  LOWER[ch] = { w: rows[0].length, rows: rows.map(r => [...r].map((c, x) => c === '#' ? x : -1).filter(x => x >= 0)) }
}

export function glyph(ch, mixed = false) {
  return (mixed && LOWER[ch]) || FONT[ch] || FONT[ch.toUpperCase()] || FONT['?']
}

export function textWidth(str, scale = 1, mixed = false) {
  let w = 0
  for (const ch of str) w += (glyph(ch, mixed).w + 1) * scale
  return Math.max(0, w - scale)
}
